// Bundle the viewer (three.js included) two ways:
//  1. commit_city/viewer.html: one HTML template the Python renderer fills with __DATA__ and __AVATAR__,
//     so CLI and Action builds need no Node.
//  2. web/public/v/app.<hash>.js + web/lib/viewer-shell.ts: the same app for commit.city, where the page
//     shell injects the payload at runtime.
// usage: node viewer/build.mjs
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const res = await build({
  entryPoints: [path.join(here, 'src/main.js')], bundle: true, format: 'iife', minify: true,
  target: 'es2020', write: false, legalComments: 'eof', logLevel: 'warning',
});
const app = res.outputFiles[0].text;
const tpl = fs.readFileSync(path.join(here, 'src/template.html'), 'utf8');
for (const ph of ['__DATA__', '__AVATAR__', '/*__APP__*/']) {
  if (!tpl.includes(ph)) throw new Error(`template is missing ${ph}`);
}

// 1. standalone template
const out = path.join(root, 'commit_city', 'viewer.html');
fs.writeFileSync(out, tpl.replace('/*__APP__*/', () => app.replace(/<\/script/gi, '<\\/script')));
console.log(`wrote ${path.relative(process.cwd(), out)} (${(fs.statSync(out).size / 1e6).toFixed(2)} MB)`);

// 2. web: hashed app file + the template's CSS and markup as a TS module
const hash = createHash('sha256').update(app).digest('hex').slice(0, 10);
const vdir = path.join(root, 'web', 'public', 'v');
fs.mkdirSync(vdir, { recursive: true });
for (const f of fs.readdirSync(vdir)) if (/^app\.[0-9a-f]+\.js$/.test(f)) fs.rmSync(path.join(vdir, f));
fs.writeFileSync(path.join(vdir, `app.${hash}.js`), app);
const css = tpl.match(/<style>([\s\S]*?)<\/style>/)[1];
const body = tpl.slice(tpl.indexOf('<div id="stage">'), tpl.indexOf('<img id="avatar-src"'));
const shell = `// Generated by viewer/build.mjs from viewer/src/template.html. Do not edit.
export const VIEWER_APP = '/v/app.${hash}.js';
export const VIEWER_CSS = ${JSON.stringify(css)};
export const VIEWER_BODY = ${JSON.stringify(body)};
`;
fs.writeFileSync(path.join(root, 'web', 'lib', 'viewer-shell.ts'), shell);
// the layout code too, so cards and link previews draw the same city the viewer does
const layout = fs.readFileSync(path.join(here, 'src', 'layout.js'), 'utf8');
fs.writeFileSync(path.join(root, 'web', 'lib', 'layout.ts'), `// @ts-nocheck\n// Generated by viewer/build.mjs from viewer/src/layout.js. Do not edit.\n${layout}`);
console.log(`wrote web/public/v/app.${hash}.js (${(app.length / 1e6).toFixed(2)} MB), web/lib/viewer-shell.ts and web/lib/layout.ts`);
