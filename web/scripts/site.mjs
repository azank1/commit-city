// Stamp the site's pages: web/site/<page>.html + the shared head, nav and footer -> web/public/<page>.html,
// plus sitemap.xml and the touch icon. The output is committed (Vercel deploys web/ with no build step);
// CI checks it is current, like the viewer build.
// usage: node scripts/site.mjs
import { Resvg } from '@resvg/resvg-js';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'site');
const pub = path.join(root, 'public');
const read = f => fs.readFileSync(f, 'utf8');
const hash = f => createHash('sha256').update(fs.readFileSync(f)).digest('hex').slice(0, 8);
const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

const GH = 'M8 0C3.58 0 0 3.58 0 8c0 3.54 2.29 6.53 5.47 7.59.4.07.55-.17.55-.38 0-.19-.01-.82-.01-1.49-2.01.37-2.53-.49-2.69-.94-.09-.23-.48-.94-.82-1.13-.28-.15-.68-.52-.01-.53.63-.01 1.08.58 1.23.82.72 1.21 1.87.87 2.33.66.07-.52.28-.87.51-1.07-1.78-.2-3.64-.89-3.64-3.95 0-.87.31-1.59.82-2.15-.08-.2-.36-1.02.08-2.12 0 0 .67-.21 2.2.82.64-.18 1.32-.27 2-.27.68 0 1.36.09 2 .27 1.53-1.04 2.2-.82 2.2-.82.44 1.1.16 1.92.08 2.12.51.56.82 1.27.82 2.15 0 3.07-1.87 3.75-3.65 3.95.29.25.54.73.54 1.48 0 1.07-.01 1.93-.01 2.2 0 .21.15.46.55.38A8.013 8.013 0 0016 8c0-4.42-3.58-8-8-8z';
const favicon = read(path.join(pub, 'favicon.svg'));
const logo = favicon.replace(/<rect[^>]*\/>/, '').replace('<svg ', '<svg aria-hidden="true" ');
const liveApp = fs.readdirSync(path.join(pub, 'v')).find(f => /^live\.[0-9a-f]+\.js$/.test(f));
if (!liveApp) throw new Error('no web/public/v/live.<hash>.js: run node viewer/build.mjs first');
const vars = { logo, ghpath: GH, cssv: hash(path.join(pub, 's/site.css')), jsv: hash(path.join(pub, 's/site.js')), liveApp: `/v/${liveApp}` };
// the agent lens's rules, as a table on /about
const rules = JSON.parse(read(path.join(root, '..', 'schema', 'agents.json')));
const SIGNALS = { author: 'commits as itself', coauthor: 'Co-authored-by trailer', message: 'message footer', login: 'GitHub account', branch: 'branch names' };
vars.agentsTable = `<div class="agents-grid">${rules.agents.map(a => `<div><b><i style="background:${esc(a.color)}"></i>${esc(a.label)}</b><small>${
  Object.keys(SIGNALS).filter(k => a[k]?.length).map(k => SIGNALS[k]).join(' · ')}</small></div>`).join('')}</div>`;
// ...and as a roster of chips on the home page
vars.agentCount = String(rules.agents.length);
vars.agentChips = rules.agents.map(a => `<span class="ag" style="--c:${esc(a.color)}"><i></i>${esc(a.label)}</span>`).join('');
const fill = (tpl, v) => tpl.replace(/\{\{(\w+)\}\}/g, (_, k) => (k in v ? v[k] : `{{${k}}}`));

const head = read(path.join(src, '_head.html'));
const nav = read(path.join(src, '_nav.html'));
const footer = read(path.join(src, '_footer.html'));
const pages = [];
for (const name of fs.readdirSync(src).filter(f => f.endsWith('.html') && !f.startsWith('_')).sort()) {
  const text = read(path.join(src, name));
  const m = text.match(/^<!--page\s+(\{[\s\S]*?\})\s*-->\n?/);
  if (!m) throw new Error(`${name}: missing <!--page {...}--> header`);
  const meta = JSON.parse(m[1]);
  let body = text.slice(m[0].length);
  let style = '';
  const sm = body.match(/^\s*<style>([\s\S]*?)<\/style>\n?/);
  if (sm) { style = sm[1].trim(); body = body.slice(sm[0].length); }
  const p = { path: '/', ogImage: '/api/og', ...meta };
  const v = { ...vars, title: esc(p.title), ogTitle: esc(p.ogTitle || p.title), description: esc(p.description), path: p.path, ogImage: esc(p.ogImage) };
  const html = `<!doctype html>
<!-- Generated by web/scripts/site.mjs from web/site/${name}. Edit the source, then run: node scripts/site.mjs -->
<html lang="en">
<head>
${fill(head, v).trim()}
${p.head ? p.head + '\n' : ''}${style ? `<style>\n${style}\n</style>\n` : ''}<script src="/s/site.js?v=${vars.jsv}" defer></script>
</head>
<body${p.bodyClass ? ` class="${p.bodyClass}"` : ''}>
${p.nav === false ? '' : fill(nav, v).trim() + '\n'}${fill(body.trim(), v)}
${p.footer === false ? '' : fill(footer, v).trim() + '\n'}</body>
</html>
`;
  fs.writeFileSync(path.join(pub, name), html);
  if (p.sitemap !== false) pages.push(p.path);
  console.log(`wrote public/${name}`);
}

fs.writeFileSync(path.join(pub, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${pages.map(p => `  <url><loc>https://commit.city${p}</loc></url>`).join('\n')}
</urlset>
`);
// home-screen icon: the favicon on its own ground, a little inset
const touch = favicon.replace('viewBox="0 0 32 32"', 'viewBox="-3 -3 38 38" width="180" height="180"').replace('<rect width="32" height="32" rx="7"', '<rect x="-3" y="-3" width="38" height="38"');
fs.writeFileSync(path.join(pub, 'apple-touch-icon.png'), new Resvg(touch).render().asPng());
console.log('wrote public/sitemap.xml, public/apple-touch-icon.png');
